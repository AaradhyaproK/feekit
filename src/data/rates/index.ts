export function getRateEntry(id: string): RateEntry {
  const entry = GATEWAY_RATES[id] || STATUTORY_TAX_RATES[id];
  if (!entry) {
    throw new Error(`Missing rate entry for id: "${id}". All rates must be defined in src/data/rates/index.ts`);
  }
  return entry;
}

export function getStateSalesTax(slug: string): StateSalesTaxEntry {
  const entry = US_STATE_SALES_TAX_RATES[slug.toLowerCase()];
  if (!entry) {
    throw new Error(`Missing state sales tax entry for slug: "${slug}". Must be defined in src/data/rates/index.ts`);
  }
  return entry;
}

export function getAllStateSalesTaxes(): StateSalesTaxEntry[] {
  return Object.values(US_STATE_SALES_TAX_RATES);
}

