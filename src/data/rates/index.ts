/**
 * FeeKit Central Source of Truth for Financial Rates, Processing Fees, and Statutory Thresholds.
 * 
 * NON-NEGOTIABLE COMPLIANCE RULES:
 * 1. Every entry MUST have a verified primary source URL (sourceUrl) and verified date (verifiedOn).
 * 2. Every figure across calculators, dropdowns, footers, meta descriptions, FAQs, and JSON-LD
 *    MUST read directly or derive from this central file.
 * 3. Never invent or guess a number.
 */

export interface RateEntry {
  id: string;
  value: number;
  unit: '%' | 'fixed_currency' | 'currency' | 'count' | 'ratio';
  currency?: string;
  label: string;
  sourceUrl: string;
  sourceName: string;
  verifiedOn: string; // ISO date YYYY-MM-DD
  notes?: string;
  jurisdiction?: string;
}

export interface StateSalesTaxEntry {
  slug: string;
  name: string;
  code: string;
  baseRate: number; // e.g. 7.25 for 7.25%
  maxCombinedRate: number; // e.g. 10.75 for 10.75%
  averageLocalRate: number; // e.g. 1.57 for 1.57%
  combinedAverageRate: number; // e.g. 8.82 for 8.82%
  economicNexusThreshold: number; // e.g. 500000
  economicNexusTransactions?: number; // e.g. 200 or undefined if revenue-only
  filingAgency: string; // abbreviation e.g. "CDTFA"
  agencyFullName: string;
  sourceUrl: string;
  sourceName: string;
  verifiedOn: string; // ISO date YYYY-MM-DD
  notes: string;
  recordRetentionYears: number; // e.g. 4 for CA under CDTFA Pub 17
  penaltyCitation: string;
  isDestinationBased: boolean;
  hasLocalSurtaxes: boolean;
}

