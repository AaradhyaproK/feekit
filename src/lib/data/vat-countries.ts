/**
 * Normalizes input code/slug to find the matching country configuration.
 * Defaults to Germany or United Kingdom if not found.
 */
export function getVatCountry(slugOrCode?: string): VatCountryConfig {
  if (!slugOrCode) return VAT_COUNTRIES['germany'];

  const cleaned = slugOrCode.toLowerCase().trim().replace(/_/g, '-');

  // Direct slug match
  if (VAT_COUNTRIES[cleaned]) {
    return VAT_COUNTRIES[cleaned];
  }

  // Code match (e.g. "DE", "GB", "FR")
  const upperCode = slugOrCode.toUpperCase().trim();
  const byCode = Object.values(VAT_COUNTRIES).find((c) => c.code === upperCode);
  if (byCode) return byCode;

  // Name match
  const byName = Object.values(VAT_COUNTRIES).find(
    (c) => c.name.toLowerCase() === cleaned
  );
  if (byName) return byName;

  // Fallback to Germany
  return VAT_COUNTRIES['germany'];
}
